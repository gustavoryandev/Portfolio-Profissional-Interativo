import { Worker } from 'node:worker_threads';
import { writeFileSync } from 'node:fs';
import assert from 'node:assert/strict';
import { Chess } from 'chess.js';
import { parseChessReplay } from '../src/services/chessReplay.js';
import { reviewChessGame, reviewPosition, gradeChessMove } from '../src/services/chessReview.js';
const createWorker = () => {
 const worker = new Worker(new URL('./chess-engine-worker.cjs', import.meta.url));
 const adapter = { postMessage: value => worker.postMessage(value), terminate: () => worker.terminate() };
 worker.on('message', data => adapter.onmessage?.({ data }));
 worker.on('error', error => adapter.onerror?.(error));
 return adapter;
};
const evaluate = (position, options) => reviewPosition(position, { ...options, mode: 'quick', multiPV: 2, createWorker });
const results = [];
const fool = parseChessReplay('1. f3 e5 2. g4 Qh4#');
await reviewChessGame(fool, { mode: 'quick', evaluate, onProgress(i, before, after, grade) { results.push({ game: 'Fools mate', move: fool.moves[i].san, grade, after }); } });
assert.equal(results.at(-1).after.terminal, 'checkmate');
const opera = new Chess();
opera.loadPgn('1. e4 e5 2. Nf3 d6 3. d4 Bg4 4. dxe5 Bxf3 5. Qxf3 dxe5 6. Bc4 Nf6 7. Qb3 Qe7 8. Nc3 c6 9. Bg5 b5 10. Nxb5 cxb5 11. Bxb5+ Nbd7 12. O-O-O Rd8 13. Rxd7 Rxd7 14. Rd1 Qe6 15. Bxd7+ Nxd7');
const before = await evaluate(opera);
const move = opera.move('Qb8+');
const after = await evaluate(opera);
const brilliant = gradeChessMove(move, before, after, before);
assert.equal(brilliant.grade, 'brilliant');
results.push({ game: 'Opera Game', move: 'Qb8+', before, after, grade: brilliant });
const forced = new Chess('7k/8/5K2/8/8/8/8/6R1 b - - 0 1');
const forcedBefore = await evaluate(forced);
const forcedMove = forced.move(forced.moves()[0]);
const forcedAfter = await evaluate(forced);
const forcedGrade = gradeChessMove(forcedMove, forcedBefore, forcedAfter, forcedBefore);
assert.equal(forcedGrade.grade, 'best');
results.push({ game: 'Forced king move', before: forcedBefore, after: forcedAfter, grade: forcedGrade });
writeFileSync('docs/chess-validation-smoke.json', JSON.stringify(results, null, 2));
console.log('Real WASM: Fool’s Mate, Opera sacrifice, forced move passed.');
